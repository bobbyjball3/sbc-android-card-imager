class _TamperingRunner(FakeRunner):
    def __init__(self, results: list[CommandResult], mnt: Path) -> None:
        super().__init__(results)
        self._mnt = mnt

    def run(
        self,
        args: Sequence[str],
        *,
        cwd: Path | str | None = None,
        env: Mapping[str, str] | None = None,
        stdin: str | None = None,
        check: bool = True,
    ) -> CommandResult:
        result = super().run(args, cwd=cwd, env=env, stdin=stdin, check=check)
        if list(args)[:5] == ["mount", "-t", "exfat", "-o", "ro"]:
            _write(self._mnt / "Cannoli/Roms/GBA/surprise.gba", b"SURPRISE")
        return result


