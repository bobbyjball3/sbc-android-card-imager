MIB = 1024 * 1024
PARTITION_BYTES = 63 * MIB
IMAGE_BYTES = 64 * MIB
LOOP = "/dev/loop7"
SETTINGS = {"path": "Cannoli/Config/settings.json", "content": "{}\n"}
CREDITS = {"path": "CREDITS.md", "content": "# Credits\n\nGenerated by sbc-imager.\n"}


def _write(path: Path, data: bytes, mtime: int | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    if mtime is not None:
        os.utime(path, ns=(mtime, mtime))
    return path


def _ok(*, stdout: str = "") -> CommandResult:
    return CommandResult((), 0, stdout, "", 0.0)


def _fail(returncode: int = 1, *, stderr: str = "boom") -> CommandResult:
    return CommandResult((), returncode, "", stderr, 0.0)


def _entry(stage_dir: Path, dest: str, data: bytes) -> dict[str, object]:
    path = _write(stage_dir / dest, data)
    return {
        "dest": dest,
        "src": str(path),
        "kind": "rom",
        "size": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


def _content_bytes(entries: list[dict[str, object]]) -> int:
    total = 0
    for entry in entries:
        size = entry["size"]
        assert isinstance(size, int)
        total += size
    return total


def _plan_payload(
    stage_dir: Path,
    entries: list[dict[str, object]],
    *,
    required_dirs: list[str] | None = None,
    label: str = "CANNOLI",
    image_bytes: int = IMAGE_BYTES,
    partition_bytes: int = PARTITION_BYTES,
    partition_offset_bytes: int = MIB,
    settings: dict[str, str] | None = None,
    credits: dict[str, str] | None = None,
) -> dict[str, object]:
    return {
        "schema_version": 1,
        "cannoli_version": "1.9.1",
        "image_bytes": image_bytes,
        "partition_bytes": partition_bytes,
        "partition_offset_bytes": partition_offset_bytes,
        "label": label,
        "required_dirs": required_dirs
        if required_dirs is not None
        else ["Cannoli", "Cannoli/Roms/GBA", "Cannoli/Roms/SNES", "APKs"],
        "settings_marker": settings if settings is not None else SETTINGS,
        "credits_marker": credits if credits is not None else CREDITS,
        "entries": entries,
        "totals": {
            "entries": len(entries),
            "content_bytes": _content_bytes(entries),
        },
    }


def _write_plan(tmp_path: Path, payload: dict[str, object]) -> Path:
    path = tmp_path / "work" / "stage-plan.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


def _success_results() -> list[CommandResult]:
    return [_ok(stdout=LOOP + "\n"), _ok(), _ok(), _ok(), _ok(), _ok(), _ok(), _ok()]


def _fixture(
    tmp_path: Path,
    *,
    entries: list[dict[str, object]] | None = None,
    image_bytes: int = IMAGE_BYTES,
    partition_bytes: int = PARTITION_BYTES,
    partition_offset_bytes: int = MIB,
) -> tuple[Path, Path, Path]:
    stage_dir = tmp_path / "stage"
    stage_dir.mkdir()
    written = entries
    if written is None:
        written = [
            _entry(stage_dir, "Cannoli/Roms/GBA/demo.gba", b"ROMDATA"),
            _entry(stage_dir, "APKs/Demo.apk", b"APK"),
        ]
    payload = _plan_payload(
        stage_dir,
        written,
        image_bytes=image_bytes,
        partition_bytes=partition_bytes,
        partition_offset_bytes=partition_offset_bytes,
    )
    plan_path = _write_plan(tmp_path, payload)
    return stage_dir, plan_path, tmp_path / "out" / "card.img"


def test_assemble_when_happy_path_builds_verified_image(tmp_path: Path) -> None:
    stage_dir, plan_path, out = _fixture(tmp_path)
    out.parent.mkdir(parents=True)
    runner = FakeRunner(_success_results())
    phases: list[tuple[str, int, int]] = []

    report = assemble(
        stage_dir,
        plan_path,
        out,
        tmp_path / "work",
        runner,
        lambda phase, current, total: phases.append((phase, current, total)),
    )

    work = tmp_path / "work"
    image = work / "image.img"
    mnt = work / "mnt"
    assert runner.commands == [
        [
            "losetup",
            "--find",
            "--show",
            "--offset",
            str(MIB),
            "--sizelimit",
            str(PARTITION_BYTES),
            str(image),
        ],
        ["mkfs.exfat", "-L", "CANNOLI", LOOP],
        ["mount", "-t", "exfat", LOOP, str(mnt)],
        ["umount", str(mnt)],
        ["fsck.exfat", "-n", LOOP],
        ["mount", "-t", "exfat", "-o", "ro", LOOP, str(mnt)],
        ["umount", str(mnt)],
        ["losetup", "-d", LOOP],
    ]
    assert (mnt / "Cannoli/Roms/GBA").is_dir()
    assert (mnt / "Cannoli/Roms/SNES").is_dir()
    assert (mnt / "APKs").is_dir()
    assert (mnt / SETTINGS["path"]).read_text(encoding="utf-8") == SETTINGS["content"]
    assert (mnt / CREDITS["path"]).read_text(encoding="utf-8") == CREDITS["content"]
    assert (mnt / "Cannoli/Roms/GBA/demo.gba").read_bytes() == b"ROMDATA"
    assert out.is_file()
    assert out.stat().st_size == IMAGE_BYTES
    assert not Path(str(out) + ".partial").exists()

    header = out.read_bytes()[:512]
    assert header[450] == 0x07
    assert int.from_bytes(header[454:458], "little") == 2048
    assert header[510:512] == b"\x55\xaa"

    tree_payload = json.loads((work / "tree.json").read_text(encoding="utf-8"))
    assert [item["dest"] for item in tree_payload] == sorted(item["dest"] for item in tree_payload)
    assert {item["dest"] for item in tree_payload} == {
        "Cannoli/Roms/GBA/demo.gba",
        "APKs/Demo.apk",
        SETTINGS["path"],
        CREDITS["path"],
    }
    tree_bytes = (work / "tree.json").read_bytes()
    report_payload = json.loads((work / "report.json").read_text(encoding="utf-8"))
    assert report_payload == {
        "schema_version": 1,
        "image_bytes": IMAGE_BYTES,
        "partition_bytes": PARTITION_BYTES,
        "partition_offset_bytes": MIB,
        "content_files": 2,
        "content_bytes": 10,
        "tree_sha256": hashlib.sha256(tree_bytes).hexdigest(),
        "fsck_ok": True,
        "label": "CANNOLI",
    }
    assert isinstance(report, Report)
    assert report.tree_sha256 == report_payload["tree_sha256"]
    assert report.fsck_ok is True
    assert {item.dest for item in report.tree} == {item["dest"] for item in tree_payload}
    assert {phase for phase, _, _ in phases} >= {"copy", "verify"}
    assert all(total == 4 for phase, _, total in phases if phase in {"copy", "verify"})
    assert phases[-1][1] == phases[-1][2]


